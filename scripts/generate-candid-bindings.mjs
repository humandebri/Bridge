import { readFile, mkdir, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const check = process.argv.includes("--check")
const uiBridgeDid = "ui/src/generated/bridge.ui.did"

const interfaces = [
  {
    name: "UI Bridge",
    did: uiBridgeDid,
    types: ["ui/src/generated/bridge.did.ts"],
    runtimes: [
      ["ui/src/generated/bridge.idl.ts", true],
    ],
  },
  {
    name: "Bridge",
    did: "canister/bridge-canister/bridge.did",
    types: [],
    runtimes: [
      ["integration/generated/bridge.idl.ts", true],
      ["ui/e2e-real/generated/bridge.idl.mjs", false],
    ],
  },
  {
    name: "mock external canister",
    did: "canister/mock-external/mock.did",
    types: [],
    runtimes: [
      ["integration/generated/mock-external.idl.ts", true],
      ["ui/e2e-real/generated/mock-external.idl.mjs", false],
    ],
  },
]

function bind(did, target) {
  const result = spawnSync("didc", ["bind", resolve(root, did), "-t", target], { encoding: "utf8" })
  if (result.status !== 0) throw new Error(result.stderr || `didc ${target} binding failed for ${did}`)
  return result.stdout
    .replaceAll("@dfinity/agent", "@icp-sdk/core/agent")
    .replaceAll("@dfinity/candid", "@icp-sdk/core/candid")
    .replaceAll("@dfinity/principal", "@icp-sdk/core/principal")
}

async function emit(path, contents) {
  const destination = resolve(root, path)
  if (check) {
    const existing = await readFile(destination, "utf8").catch(() => "")
    if (existing !== contents) throw new Error(`${path} is stale; run pnpm --dir ui codegen:candid`)
    return
  }
  await mkdir(dirname(destination), { recursive: true })
  await writeFile(destination, contents)
}

function browserBridgeInterface(source) {
  const projected = source
    .replace(/type BridgeInitArgs = record \{[\s\S]*?\n\};\n/, "")
    .replace(/type ControlPlaneAddressesError = variant \{[\s\S]*?\n\};\n/, "")
    .replace(/type ControlPlaneAddressesView = record \{[\s\S]*?\n\};\n/, "")
    .replace(/type OperationalConfig = record \{[\s\S]*?\n\};\n/, "")
    .replace(/type OperationalConfigError = variant \{ Unauthorized \};\n/, "")
    .replace(/type Result_9 = variant \{\n  Ok : ControlPlaneAddressesView;\n  Err : ControlPlaneAddressesError;\n\};\n/, "")
    .replace(/type Result_10 = variant \{\n  Ok : OperationalConfig;\n  Err : OperationalConfigError;\n\};\n/, "")
    .replace(/  get_control_plane_addresses : \(\) -> \(Result_9\) query;\n/, "")
    .replace(/  get_operational_config : \(\) -> \(Result_10\) query;\n/, "")
    .replace(/\bResult_(\d+)\b/g, (name, index) => Number(index) >= 10 ? `Result_${Number(index) - 1}` : name)
    .replace("service : (BridgeInitArgs) -> {", "service : {")
  if (projected.includes("type OperationalConfig =")
    || projected.includes("type OperationalConfigError =")
    || projected.includes("type ControlPlaneAddressesView =")
    || projected.includes("type ControlPlaneAddressesError =")
    || projected.includes("get_control_plane_addresses")
    || projected.includes("get_operational_config")
    || projected.includes("confirmation_relayer_principal")) {
    throw new Error("UI Bridge projection still exposes operational configuration")
  }
  return `// Generated from canister/bridge-canister/bridge.did. Do not edit.\n${projected}`
}

const fullBridgeDid = await readFile(resolve(root, "canister/bridge-canister/bridge.did"), "utf8")
await emit(uiBridgeDid, browserBridgeInterface(fullBridgeDid))

for (const definition of interfaces) {
  const header = `/* Generated by didc from ${definition.did}. Do not edit. */\n`
  const types = definition.types.length > 0 ? bind(definition.did, "ts") : ""
  const runtime = bind(definition.did, "js")
  for (const path of definition.types) await emit(path, `${header}${types}`)
  for (const [path, isTypeScript] of definition.runtimes) {
    const contents = isTypeScript
      ? runtime.replaceAll(
          "({ IDL }) =>",
          '({ IDL }: Parameters<import("@icp-sdk/core/candid").IDL.InterfaceFactory>[0]) =>',
        ).replace(
          '({ IDL }: Parameters<import("@icp-sdk/core/candid").IDL.InterfaceFactory>[0]) => { return []; }',
          '(_idl: Parameters<import("@icp-sdk/core/candid").IDL.InterfaceFactory>[0]) => { return []; }',
        )
      : runtime
    await emit(path, `${header}${contents}`)
  }
  process.stdout.write(`${check ? "checked" : "generated"} ${definition.name} Candid bindings\n`)
}
