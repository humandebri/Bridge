import { readFile, mkdir, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { spawnSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const check = process.argv.includes("--check")

const interfaces = [
  {
    name: "Bridge",
    did: "canister/bridge-canister/bridge.did",
    types: ["ui/src/generated/bridge.did.ts"],
    runtimes: [
      ["ui/src/generated/bridge.idl.ts", true],
      ["integration/generated/bridge.idl.ts", true],
      ["ui/e2e-real/generated/bridge.idl.mjs", false],
    ],
  },
  {
    name: "mock external canister",
    did: "canister/mock-external/mock.did",
    types: [],
    runtimes: [
      ["integration/generated/mock-external.idl.ts", true],
      ["ui/e2e-real/generated/mock-external.idl.mjs", false],
    ],
  },
]

function bind(did, target) {
  const result = spawnSync("didc", ["bind", resolve(root, did), "-t", target], { encoding: "utf8" })
  if (result.status !== 0) throw new Error(result.stderr || `didc ${target} binding failed for ${did}`)
  return result.stdout
}

async function emit(path, contents) {
  const destination = resolve(root, path)
  if (check) {
    const existing = await readFile(destination, "utf8").catch(() => "")
    if (existing !== contents) throw new Error(`${path} is stale; run pnpm --dir ui codegen:candid`)
    return
  }
  await mkdir(dirname(destination), { recursive: true })
  await writeFile(destination, contents)
}

for (const definition of interfaces) {
  const header = `/* Generated by didc from ${definition.did}. Do not edit. */\n`
  const types = definition.types.length > 0 ? bind(definition.did, "ts") : ""
  const runtime = bind(definition.did, "js")
  for (const path of definition.types) await emit(path, `${header}${types}`)
  for (const [path, isTypeScript] of definition.runtimes) {
    await emit(path, `${header}${isTypeScript ? "// @ts-nocheck\n" : ""}${runtime}`)
  }
  process.stdout.write(`${check ? "checked" : "generated"} ${definition.name} Candid bindings\n`)
}
